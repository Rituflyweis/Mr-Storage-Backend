const PDFDocument = require('pdfkit')
const Expense = require('../models/Expense')
const { getInvoiceCompany } = require('../config/invoiceCompany')

const PAGE_MARGIN = 48
const HEADER_COLOR = '#1a2e4a'

const formatMoney = (n) =>
  new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(Number(n || 0))

const formatDate = (d) => {
  if (!d) return '—'
  return new Date(d).toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' })
}

const drawKeyValueRow = (doc, label, value, { labelWidth = 160 } = {}) => {
  const y = doc.y
  doc.font('Helvetica').fontSize(10).fillColor('#666666').text(label, PAGE_MARGIN, y, { width: labelWidth })
  doc.font('Helvetica-Bold').fillColor(HEADER_COLOR).text(String(value ?? '—'), PAGE_MARGIN + labelWidth, y, {
    width: doc.page.width - PAGE_MARGIN * 2 - labelWidth,
    align: 'right',
  })
  doc.moveDown(0.4)
}

const buildSalaryPayslipPdfBuffer = (expense) => {
  const company = getInvoiceCompany()
  const meta = expense.metadata || {}
  const employeeName = meta.employeeName || expense.description || 'Employee'
  const employeeId = meta.employeeId || expense.buildingLabel || '—'
  const designation = meta.designation || expense.subcategory || '—'
  const netSalary = Number(expense.amount) || 0
  const statusLabel = expense.status === 'paid' ? 'Paid' : 'Unpaid'

  const doc = new PDFDocument({ margin: PAGE_MARGIN, size: 'A4' })
  const buffers = []
  doc.on('data', (chunk) => buffers.push(chunk))

  return new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(buffers)))
    doc.on('error', reject)

    const contentWidth = doc.page.width - PAGE_MARGIN * 2

    doc.font('Helvetica-Bold').fontSize(16).fillColor('#1a1a1a').text(company.name || 'STEEL BUILDING DEPOT', PAGE_MARGIN)
    doc.moveDown(0.3)
    doc.font('Helvetica').fontSize(9).fillColor('#666666').text('Salary payslip', PAGE_MARGIN)
    doc.moveDown(1.2)

    doc.rect(PAGE_MARGIN, doc.y, contentWidth, 56).fill(HEADER_COLOR)
    const boxY = doc.y + 14
    doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(18).text('Payslip', PAGE_MARGIN + 16, boxY)
    doc.font('Helvetica').fontSize(10).text(`Reference: ${expense.expenseId}`, PAGE_MARGIN + 16, boxY + 26)
    doc.moveDown(4)

    doc.fillColor(HEADER_COLOR).font('Helvetica-Bold').fontSize(11).text('Employee')
    doc.moveDown(0.4)
    drawKeyValueRow(doc, 'Name', employeeName)
    drawKeyValueRow(doc, 'Employee ID', employeeId)
    drawKeyValueRow(doc, 'Designation', designation)
    drawKeyValueRow(doc, 'Pay period date', formatDate(expense.date))

    doc.moveDown(0.6)
    doc.fillColor(HEADER_COLOR).font('Helvetica-Bold').fontSize(11).text('Payment')
    doc.moveDown(0.4)
    drawKeyValueRow(doc, 'Net salary', formatMoney(netSalary))
    drawKeyValueRow(doc, 'Payment status', statusLabel)
    drawKeyValueRow(doc, 'Admin approval', meta.adminApproval || (expense.status === 'paid' ? 'Approved' : 'Pending'))

    doc.moveDown(1)
    doc.font('Helvetica').fontSize(9).fillColor('#888888').text(
      'This document is generated by the account expenses system for internal payroll records.',
      PAGE_MARGIN,
      doc.y,
      { width: contentWidth }
    )

    doc.end()
  })
}

exports.getSalaryExpenseForPayslip = async (id) =>
  Expense.findOne({ _id: id, costPanelType: 'salary', isActive: true })

exports.generateSalaryPayslip = async (id) => {
  const expense = await exports.getSalaryExpenseForPayslip(id)
  if (!expense) return null

  const buffer = await buildSalaryPayslipPdfBuffer(expense)
  expense.metadata = {
    ...(expense.metadata || {}),
    payslipGeneratedAt: new Date(),
    payslipFileName: `payslip-${expense.expenseId}.pdf`,
  }
  expense.markModified('metadata')
  await expense.save()

  return { expense, buffer }
}

exports.getSalaryPayslipPdfBuffer = async (id, { regenerate = false } = {}) => {
  const expense = await exports.getSalaryExpenseForPayslip(id)
  if (!expense) return null

  if (!regenerate && expense.metadata?.payslipGeneratedAt) {
    return { expense, buffer: await buildSalaryPayslipPdfBuffer(expense) }
  }

  const buffer = await buildSalaryPayslipPdfBuffer(expense)
  return { expense, buffer }
}

exports.buildSalaryPayslipPdfBuffer = buildSalaryPayslipPdfBuffer
